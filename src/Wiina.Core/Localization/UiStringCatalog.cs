    public static string Get(string key, string? language = null)
    {
        Entry entry = Entries.TryGetValue(key, out Entry? found)
            ? found
            : throw new KeyNotFoundException($"Localization key not found: {key}");
        return AppLanguage.NormalizeTag(language) == AppLanguage.English ? entry.English : entry.ZhHans;
    }

    public static string Format(string key, string? language, params object?[] args) =>
        string.Format(CultureInfo.InvariantCulture, Get(key, language), args);

    public static bool TryGet(string key, string? language, out string text)
    {
        if (!Entries.TryGetValue(key, out Entry? entry))
        {
            text = string.Empty;
            return false;
        }

        text = AppLanguage.NormalizeTag(language) == AppLanguage.English ? entry.English : entry.ZhHans;
        return true;
    }

